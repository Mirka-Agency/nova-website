/**
 * @param {string} identifier
 * @param {'good'|'ok'|'bad'|'feedback'|'error'|string} rating
 */
export function copyFor(identifier, rating) {
  const c = YOAST_FA_COPY[identifier];
  if (!c) {
    return {
      title: identifier,
      description: '',
      fix: '',
    };
  }

  const r = rating === 'good' ? 'good' : rating === 'ok' || rating === 'feedback' ? 'ok' : 'bad';
  const description = c[r] || c.ok || c.bad;
  const fixKey = r === 'good' ? 'fixGood' : r === 'ok' ? 'fixOk' : 'fixBad';
  return {
    title: c.title,
    description,
    fix: c[fixKey] || '',
  };
}
